"""Summarize real monitor outputs from independently generated scoring runs (never invent incidents).

python -m scripts.summarize_evaluation --runs /path/to/runs --seeds 4,8 --out docs/results.md
Expected files: seed<N>.db and seed<N>-incidents/*.json, produced by sim.score generate and brain.run --replay.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import pandas as pd
from sim import score as sc


def main(argv=None):
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--runs',type=Path,required=True)
    ap.add_argument('--seeds',default='4,8')
    ap.add_argument('--out',type=Path,default=Path('docs/results.md'))
    args=ap.parse_args(argv)
    seeds=[int(s) for s in args.seeds.split(',')]
    if len(set(seeds))!=len(seeds):ap.error('seeds must be distinct')
    reports=[]
    for seed in seeds:
        path=args.runs/f'seed{seed}.db'
        if not path.is_file():ap.error(f'missing database: {path}')
        events,start,end=sc.load_truth(path)
        inc=sc.load_incidents(args.runs/f'seed{seed}-incidents')
        days=(end-start+pd.Timedelta(hours=1))/pd.Timedelta(days=1)
        result=sc.score(events,inc,end,days)
        reports.append(dict(seed=seed,days=days,**result))
    faults=sum(r['faults'] for r in reports);detected=sum(r['detected'] for r in reports)
    false=sum(r['false_alarms'] for r in reports);days=sum(r['days'] for r in reports)
    innocents=sum(r['innocents'] for r in reports);silent=sum(r['innocents_silent'] for r in reports)
    correct=sum(sum(p.get('correct_cause',False) for p in r['per_fault']) for r in reports)
    localized=sum(sum(p.get('localized',False) for p in r['per_fault']) for r in reports)
    delays=[p['delay_h'] for r in reports for p in r['per_fault'] if p['detected']]
    mean=sum(delays)/len(delays) if delays else None
    lines=['# Results — simulated marketplace','',
        'Generated by `python -m scripts.summarize_evaluation` from actual `brain.run --replay` incident files.',
        'Synthetic data, 21 clean baseline days per run, routine deployments included. These are engineering checks, not production or independent holdout performance: seeds 4–8 were previously used by B; the 49-day schedule differs from the earlier 28-day harness.','',
        '| Run | Faults detected | Correct supported cause | False alarms | Innocent events silent |',
        '|---|---:|---:|---:|---:|']
    for r in reports:
        c=sum(p.get('correct_cause',False) for p in r['per_fault'])
        lines.append(f"| Seed {r['seed']}, {r['days']:.0f} days | {r['detected']}/{r['faults']} | {c}/{r['detected']} detected | {r['false_alarms']} | {r['innocents_silent']}/{r['innocents']} |")
    lines += ['',f'Total: {detected}/{faults} faults detected ({sc.pct(detected/faults if faults else None)}), {localized}/{detected} localized to the injected scope, {correct}/{detected} with the correct supported cause.',
        f'False alarms: {false} over {days:.0f} simulated days ({false/days:.3f}/day). Innocent changes silent: {silent}/{innocents}.',
        f'Mean delay after the first affected data hour: {mean:.2f} simulated hours (0 means caught in the first bad hour).' if mean is not None else 'Mean delay: n/a.',
        '', '## Misses and unsupported causes', '']
    for r in reports:
        for p in r['per_fault']:
            if p['detected'] and p['correct_cause']:continue
            why='not detected (no matching monitor incident)' if not p['detected'] else 'detected and localized; cause not confirmed'
            scope = ', '.join(f'{d}={p["fault"][d]}' for d in sc.DIMS if d in p['fault'])
            lines.append(f"- Seed {r['seed']}: {p['kind']} at {p['fault'].get('start')}, {scope}: {why}.")
    lines += ['', '## Limits', '',
        '- Delay steps and promo checks use the agreed logical clock/completeness labels. Late source values remain complete in facts_hourly; this does not test genuinely missing payloads.',
        '- Full added-metric watcher/validation/export and competing-cause investigation are not validated by these runs.',
        '- Replays test detection across synthetic hours. Wall-clock mode follows real time and cannot compress multi-hour recovery into seconds.']
    args.out.parent.mkdir(parents=True,exist_ok=True)
    args.out.write_text('\n'.join(lines)+'\n')
    args.out.with_suffix('.json').write_text(json.dumps(reports,indent=2,default=str)+'\n')
    print(f'{args.out}: {detected}/{faults} detected; {false} false alarms; {silent}/{innocents} innocent events silent')
    return 0

if __name__=='__main__':raise SystemExit(main())
